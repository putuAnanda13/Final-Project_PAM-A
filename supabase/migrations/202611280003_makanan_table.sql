-- Use the PRD table name and columns. If the earlier app table exists, rename
-- it and its columns so existing food logs are kept.
do $$
begin
    if to_regclass('public.makanan') is null and to_regclass('public.food_logs') is not null then
        alter table public.food_logs rename to makanan;
    end if;

    if to_regclass('public.makanan') is not null then
        if exists (select 1 from information_schema.columns where table_schema='public' and table_name='makanan' and column_name='food_name')
           and not exists (select 1 from information_schema.columns where table_schema='public' and table_name='makanan' and column_name='nama_makanan') then
            alter table public.makanan rename column food_name to nama_makanan;
        end if;
        if exists (select 1 from information_schema.columns where table_schema='public' and table_name='makanan' and column_name='meal_type')
           and not exists (select 1 from information_schema.columns where table_schema='public' and table_name='makanan' and column_name='kategori') then
            alter table public.makanan rename column meal_type to kategori;
        end if;
        if exists (select 1 from information_schema.columns where table_schema='public' and table_name='makanan' and column_name='portion')
           and not exists (select 1 from information_schema.columns where table_schema='public' and table_name='makanan' and column_name='jumlah_porsi') then
            alter table public.makanan rename column portion to jumlah_porsi;
        end if;
        if exists (select 1 from information_schema.columns where table_schema='public' and table_name='makanan' and column_name='calories')
           and not exists (select 1 from information_schema.columns where table_schema='public' and table_name='makanan' and column_name='kalori') then
            alter table public.makanan rename column calories to kalori;
        end if;
        if exists (select 1 from information_schema.columns where table_schema='public' and table_name='makanan' and column_name='protein_g')
           and not exists (select 1 from information_schema.columns where table_schema='public' and table_name='makanan' and column_name='protein') then
            alter table public.makanan rename column protein_g to protein;
        end if;
        if exists (select 1 from information_schema.columns where table_schema='public' and table_name='makanan' and column_name='carbs_g')
           and not exists (select 1 from information_schema.columns where table_schema='public' and table_name='makanan' and column_name='karbohidrat') then
            alter table public.makanan rename column carbs_g to karbohidrat;
        end if;
        if exists (select 1 from information_schema.columns where table_schema='public' and table_name='makanan' and column_name='fat_g')
           and not exists (select 1 from information_schema.columns where table_schema='public' and table_name='makanan' and column_name='lemak') then
            alter table public.makanan rename column fat_g to lemak;
        end if;
        if exists (select 1 from information_schema.columns where table_schema='public' and table_name='makanan' and column_name='logged_date')
           and not exists (select 1 from information_schema.columns where table_schema='public' and table_name='makanan' and column_name='waktu_konsumsi') then
            alter table public.makanan rename column logged_date to waktu_konsumsi;
        end if;
    end if;
end;
$$;

create table if not exists public.makanan (
    id bigint generated by default as identity primary key,
    user_id uuid not null default auth.uid() references public.profile (id) on delete cascade,
    nama_makanan text not null,
    kategori text not null,
    jumlah_porsi numeric,
    kalori numeric not null,
    protein numeric,
    karbohidrat numeric,
    lemak numeric,
    gambar_url text,
    waktu_konsumsi timestamptz not null default now(),
    created_at timestamptz not null default now()
);

alter table public.makanan add column if not exists gambar_url text;
alter table public.makanan add column if not exists created_at timestamptz not null default now();

do $$
declare
    col_name text;
    column_type text;
    time_type text;
    user_fk record;
begin
    foreach col_name in array array['jumlah_porsi', 'kalori', 'protein', 'karbohidrat', 'lemak'] loop
        select c.data_type into column_type from information_schema.columns c
         where c.table_schema='public' and c.table_name='makanan' and c.column_name = col_name;
        if column_type is not null and column_type not in ('numeric', 'decimal') then
            if col_name = 'jumlah_porsi' then
                execute 'alter table public.makanan alter column jumlah_porsi type numeric using nullif(replace(regexp_replace(jumlah_porsi::text, ''[^0-9,.-]'', '''', ''g''), '','', ''.''), '''')::numeric';
            else
                execute format('alter table public.makanan alter column %I type numeric using %I::numeric', col_name, col_name);
            end if;
        end if;
    end loop;

    select data_type into time_type from information_schema.columns
     where table_schema='public' and table_name='makanan' and column_name='waktu_konsumsi';
    if time_type = 'date' then
        alter table public.makanan alter column waktu_konsumsi type timestamptz
        using waktu_konsumsi::timestamp at time zone current_setting('TIMEZONE');
    elsif time_type = 'timestamp without time zone' then
        alter table public.makanan alter column waktu_konsumsi type timestamptz
        using waktu_konsumsi at time zone current_setting('TIMEZONE');
    elsif time_type = 'text' then
        alter table public.makanan alter column waktu_konsumsi type timestamptz
        using nullif(waktu_konsumsi, '')::timestamptz;
    end if;

    for user_fk in
        select conname from pg_constraint
        where conrelid = 'public.makanan'::regclass
          and contype = 'f'
          and pg_get_constraintdef(oid) like 'FOREIGN KEY (user_id)%'
    loop
        execute format('alter table public.makanan drop constraint %I', user_fk.conname);
    end loop;
end;
$$;

alter table public.makanan
