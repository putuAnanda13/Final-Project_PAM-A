-- Ensure an existing int8 id column is generated by a sequence, and remove an
-- incompatible UUID default left by an earlier schema.
do $$
declare
    id_type text;
    id_identity text;
    id_default text;
    max_id bigint;
begin
    select c.data_type, c.is_identity, c.column_default
      into id_type, id_identity, id_default
      from information_schema.columns c
     where c.table_schema = 'public'
       and c.table_name = 'makanan'
       and c.column_name = 'id';

    if id_type <> 'bigint' then
        raise exception 'public.makanan.id harus bertipe bigint/int8, saat ini: %', id_type;
    end if;

    if id_identity = 'NO' and (id_default is null or id_default ilike '%gen_random_uuid%') then
        alter table public.makanan alter column id drop default;
        create sequence if not exists public.makanan_id_seq;
        select max(id) into max_id from public.makanan;
        if max_id is null then
            perform setval('public.makanan_id_seq', 1, false);
        else
            perform setval('public.makanan_id_seq', max_id, true);
        end if;
        alter table public.makanan alter column id set default nextval('public.makanan_id_seq');
        alter sequence public.makanan_id_seq owned by public.makanan.id;
    end if;
end;
$$;

